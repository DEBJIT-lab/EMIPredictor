from mlflow.tracking import MlflowClient

# Initialize MLflow Client
client = MlflowClient()

# Define model names for registration
cls_model_name = "EMI_Eligibility_XGBoost_Classifier"
# Corrected: The run name for the regression model was 'EMI_Amount_XGBoost_Regression'
reg_model_name = "EMI_Amount_XGBoost_Regression"

# Find the run ID for the best classification model (XGBoost Classifier)
# Assuming the latest run for 'EMI_Eligibility_XGBoost_Classifier' is the one we want to register.
# In a real scenario, you would select based on the best metric from MLflow UI comparison.
cls_runs = client.search_runs(
    experiment_ids=client.get_experiment_by_name("Default").experiment_id,
    filter_string=f"tags.mlflow.runName = '{cls_model_name}'",
    order_by=["metrics.accuracy DESC"], # Order by accuracy to pick the best if multiple runs exist
    max_results=1
)

if cls_runs:
    best_cls_run_id = cls_runs[0].info.run_id
    print(f"Found best classification run ID: {best_cls_run_id}")
    # Register the model
    registered_cls_model = mlflow.register_model(
        model_uri=f"runs:/{best_cls_run_id}/xgboost_classifier_model",
        name=cls_model_name
    )
    print(f"Registered Classification Model: {registered_cls_model.name}, Version: {registered_cls_model.version}")
else:
    print(f"Could not find a run for classification model: {cls_model_name}")

