"""Now, let's import the necessary libraries."""

import pandas as pd
import numpy as np
import sklearn
import mlflow
print('Libraries imported successfully!')

"""Since no specific dataset was provided, I will generate a synthetic dataset with approximately 400,000 records and 22 financial and demographic variables, including target variables for EMI eligibility (classification) and maximum EMI amount (regression). This will allow us to simulate the project's requirements.

### Synthetic Data Generation
"""

# Reload the dataset to start fresh
df = pd.read_csv('/content/emi_prediction_dataset.csv')

# Identify columns that should be numeric but are object type
df['age'] = pd.to_numeric(df['age'], errors='coerce')
df['monthly_salary'] = pd.to_numeric(df['monthly_salary'], errors='coerce')
df['bank_balance'] = pd.to_numeric(df['bank_balance'], errors='coerce')

# Convert 'existing_loans' from 'Yes'/'No' to 1/0 using .replace()
df['existing_loans'] = df['existing_loans'].replace({'Yes': 1, 'No': 0})

# Convert 'emi_eligibility' to numerical:
# Map 'Eligible' to 1, and 'Not_Eligible'/'High_Risk' to 0
df['emi_eligibility'] = df['emi_eligibility'].replace({'Eligible': 1, 'Not_Eligible': 0, 'High_Risk': 0})

print('\nData types after initial conversion:')
display(df.info())

print('\nMissing values after initial conversion and target mapping:')
display(df.isnull().sum())

# Drop rows where 'emi_eligibility' is still NaN (should be none after improved mapping), as it's a target variable
df.dropna(subset=['emi_eligibility'], inplace=True)

# Handle remaining missing values:
# Impute numerical columns with their median
for col in ['age', 'monthly_salary', 'monthly_rent', 'credit_score', 'bank_balance', 'emergency_fund', 'existing_loans']:
    if df[col].isnull().any():
        df[col] = df[col].fillna(df[col].median())

# Impute categorical columns with their mode
for col in ['education']:
    if df[col].isnull().any():
        df[col] = df[col].fillna(df[col].mode()[0])

# Convert 'emi_eligibility' to integer type after dropping NaNs and imputation
df['emi_eligibility'] = df['emi_eligibility'].astype(int)

print('\nMissing values after imputation and target row drop:')
display(df.isnull().sum())

print('\nDescriptive statistics for numerical features:')
display(df.describe())

print('\nFirst few rows after preprocessing:')
display(df.head())

# Identify categorical columns for one-hot encoding
categorical_cols = df.select_dtypes(include='object').columns
print(f"Categorical columns identified for one-hot encoding: {list(categorical_cols)}")

# Apply one-hot encoding
df_encoded = pd.get_dummies(df, columns=categorical_cols, drop_first=True)

print(f"\nShape of DataFrame after one-hot encoding: {df_encoded.shape}")
display(df_encoded.head())

# Separate features (X) and target variables (y)
X = df_encoded.drop(['emi_eligibility', 'max_monthly_emi'], axis=1)
y_eligible = df_encoded['emi_eligibility'] # Classification target
y_amount = df_encoded['max_monthly_emi'] # Regression target

print(f"\nShape of features (X): {X.shape}")
print(f"Shape of EMI eligibility target (y_eligible): {y_eligible.shape}")
print(f"Shape of Max EMI amount target (y_amount): {y_amount.shape}")

"""### 3.1 EMI Eligibility Prediction (Classification Model)

First, let's split our data into training and testing sets for the classification task. We'll use a `LogisticRegression` model as a baseline for EMI eligibility prediction.
"""

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

# Split data for classification
X_train_cls, X_test_cls, y_train_cls, y_test_cls = train_test_split(X, y_eligible, test_size=0.2, random_state=42)

print("Data split for Classification:")
print(f"X_train_cls shape: {X_train_cls.shape}")
print(f"y_train_cls shape: {y_train_cls.shape}")
print(f"X_test_cls shape: {X_test_cls.shape}")
print(f"y_test_cls shape: {y_test_cls.shape}")

# Initialize and train Logistic Regression model
cls_model = LogisticRegression(random_state=42, solver='liblinear', C=0.1, max_iter=1000)

# Start MLflow run for classification model
with mlflow.start_run(run_name="EMI_Eligibility_Logistic_Regression") as run:
    mlflow.log_param("model_type", "LogisticRegression")
    mlflow.log_param("solver", "liblinear")
    mlflow.log_param("C", 0.1)
    mlflow.log_param("max_iter", 1000)

    cls_model.fit(X_train_cls, y_train_cls)
    y_pred_cls = cls_model.predict(X_test_cls)
    y_pred_proba_cls = cls_model.predict_proba(X_test_cls)[:, 1]

    # Evaluate classification model
    accuracy = accuracy_score(y_test_cls, y_pred_cls)
    precision = precision_score(y_test_cls, y_pred_cls)
    recall = recall_score(y_test_cls, y_pred_cls)
    f1 = f1_score(y_test_cls, y_pred_cls)
    roc_auc = roc_auc_score(y_test_cls, y_pred_proba_cls)

    print(f"\nClassification Model Metrics:")
    print(f"Accuracy: {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall: {recall:.4f}")
    print(f"F1-Score: {f1:.4f}")
    print(f"ROC AUC Score: {roc_auc:.4f}")

    # Log metrics to MLflow
    mlflow.log_metric("accuracy", accuracy)
    mlflow.log_metric("precision", precision)
    mlflow.log_metric("recall", recall)
    mlflow.log_metric("f1_score", f1)
    mlflow.log_metric("roc_auc_score", roc_auc)

    # Log the model
    mlflow.sklearn.log_model(cls_model, "logistic_regression_model")
    print(f"MLflow Run ID: {run.info.run_id}")
    print(f"MLflow Artifact URI: {mlflow.get_artifact_uri()}")

"""### 3.2 Maximum EMI Amount Prediction (Regression Model)

Now, let's prepare the data and train a regression model to predict the `max_monthly_emi` amount. We'll start with a `LinearRegression` model as a baseline and also log its metrics to MLflow.
"""

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score, mean_absolute_error

# Split data for regression
X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(X, y_amount, test_size=0.2, random_state=42)

print("Data split for Regression:")
print(f"X_train_reg shape: {X_train_reg.shape}")
print(f"y_train_reg shape: {y_train_reg.shape}")
print(f"X_test_reg shape: {X_test_reg.shape}")
print(f"y_test_reg shape: {y_test_reg.shape}")

# Initialize and train Linear Regression model
reg_model = LinearRegression()

# Start MLflow run for regression model
with mlflow.start_run(run_name="EMI_Amount_Linear_Regression") as run:
    mlflow.log_param("model_type", "LinearRegression")

    reg_model.fit(X_train_reg, y_train_reg)
    y_pred_reg = reg_model.predict(X_test_reg)

    # Evaluate regression model
    mse = mean_squared_error(y_test_reg, y_pred_reg)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y_test_reg, y_pred_reg)
    r2 = r2_score(y_test_reg, y_pred_reg)

    print(f"\nRegression Model Metrics:")
    print(f"Mean Squared Error (MSE): {mse:.4f}")
    print(f"Root Mean Squared Error (RMSE): {rmse:.4f}")
    print(f"Mean Absolute Error (MAE): {mae:.4f}")
    print(f"R2 Score: {r2:.4f}")

    # Log metrics to MLflow
    mlflow.log_metric("mse", mse)
    mlflow.log_metric("rmse", rmse)
    mlflow.log_metric("mae", mae)
    mlflow.log_metric("r2_score", r2)

    # Log the model
    mlflow.sklearn.log_model(reg_model, "linear_regression_model")
    print(f"MLflow Run ID: {run.info.run_id}")
    print(f"MLflow Artifact URI: {mlflow.get_artifact_uri()}")

